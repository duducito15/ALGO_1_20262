public class VariablesEnteras {
    public static void main(String[] args) {
        int numero; // Declaramos la variable numero como entera

        numero = 5; // Asiganamos un valor a la variable numero

        System.out.println("El valor de mi variable es: " + numero);

        numero = 150;

        System.out.println("El nuevo valor de mi variable es: " + numero);

    }
}
